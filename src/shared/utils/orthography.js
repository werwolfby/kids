/**
 * Алфавиты и правила орфографии для трёх языков: русского, белорусского
 * и украинского.
 *
 * Модуль знает, какие буквы бывают гласными/согласными в каждом языке и какие
 * сочетания «согласная + гласная» орфографически невозможны, — чтобы генератор
 * слогов никогда не показывал ребёнку несуществующий слог (ЖЫ, ЧЯ, ТЯ…).
 *
 * ------------------------------------------------------------------ русский
 * 1. ЖИ, ШИ (никогда ЖЫ, ШЫ)
 * 2. ЧА, ЩА (никогда ЧЯ, ЩЯ)
 * 3. ЧУ, ЩУ (никогда ЧЮ, ЩЮ)
 * 4. После Ж, Ш, Ч, Щ, Ц не пишется Э
 *
 * ------------------------------------------------------------- беларуская
 * 1. Ж, Ш, Ч, Р — заўсёды цвёрдыя: пішам ЖЫ, ШЫ, ЧЫ, РЫ і ЖЭ, ШЭ, ЧЭ, РЭ
 *    (ніколі ЖІ, ШЯ, ЧЮ, РЕ).
 * 2. Дзеканне і цеканне: мяккіх Д і Т няма — замест іх ДЗ і Ц
 *    (дзень, ціха), таму спалучэнняў ДЯ, ДІ, ТЮ, ТЬ не бывае.
 * 3. Г, К, Х мяккія толькі перад І і Е (кіно, гераіня); з Я, Ё, Ю, Ы яны
 *    не спалучаюцца.
 * 4. Няма літар И, Щ, Ъ; ёсць І і Ў (Ў ніколі не пачынае склад).
 *
 * -------------------------------------------------------------- українська
 * 1. Ж, Ч, Ш, Щ — завжди тверді: ЖИ, ЧИ, ШИ, ЩИ, а також ЖІ, ЧІ, ШІ, ЩІ,
 *    але ніколи ЖЯ, ЧЮ, ШЄ.
 * 2. Ї ніколи не стоїть після приголосної (їжак, мої, з'їв).
 * 3. Г, К, Х тверді: немає ГЯ, КЮ, ХЄ.
 * 4. Немає літер Ы, Э, Ё, Ъ; є І, Ї, Є, Ґ (Ґ рідкісна — у складах не беремо).
 */

import { DEFAULT_LANGUAGE } from '../i18n/languages.js';

/** Собирает список «запрещённых» слогов из карты {согласная: [гласные]}. */
const buildInvalid = (map) => {
  const list = [];
  for (const [consonant, vowels] of Object.entries(map)) {
    for (const vowel of vowels) list.push(consonant + vowel);
  }
  return list;
};

const RU = {
  consonants: [
    'б', 'в', 'г', 'д', 'ж', 'з', 'к', 'л', 'м', 'н',
    'п', 'р', 'с', 'т', 'ф', 'х', 'ц', 'ч', 'ш', 'щ'
  ],
  vowels: ['а', 'о', 'у', 'ы', 'э', 'я', 'ё', 'ю', 'и', 'е'],
  // Ы не начинает слог, поэтому в порядке «Гласная + Согласная» её не берём.
  nonInitialVowels: ['ы'],
  softSign: 'ь',
  // Знаки, которые не являются буквами-звуками (нужны для разбивки на склады)
  signs: ['ь', 'ъ'],
  // Мягкий знак не ставится после заднеязычных и Ц
  softSignInvalidConsonants: ['г', 'к', 'х', 'ц'],
  invalidSyllables: buildInvalid({
    ж: ['ы', 'я', 'ю', 'э'],
    ш: ['ы', 'я', 'ё', 'ю', 'э'],
    ч: ['ы', 'я', 'ю', 'э'],
    щ: ['ы', 'я', 'ю', 'э'],
    ц: ['я', 'ё', 'ю', 'э']
  }),
  letterPattern: /[а-яё]/i
};

const BE = {
  // Ў і Й ніколі не пачынаюць склад, таму ў генератары складоў іх няма.
  consonants: [
    'б', 'в', 'г', 'д', 'ж', 'з', 'к', 'л', 'м', 'н',
    'п', 'р', 'с', 'т', 'ф', 'х', 'ц', 'ч', 'ш'
  ],
  vowels: ['а', 'о', 'у', 'ы', 'э', 'я', 'ё', 'ю', 'і', 'е'],
  nonInitialVowels: ['ы'],
  softSign: 'ь',
  signs: ['ь', 'ʼ', '’', "'"],
  // Мяккі знак пішацца толькі пасля З, Л, Н, С, Ц
  softSignInvalidConsonants: ['б', 'п', 'в', 'м', 'ф', 'г', 'к', 'х', 'д', 'т', 'ж', 'ш', 'ч', 'р'],
  invalidSyllables: buildInvalid({
    // заўсёды цвёрдыя
    ж: ['я', 'ё', 'ю', 'е', 'і'],
    ш: ['я', 'ё', 'ю', 'е', 'і'],
    ч: ['я', 'ё', 'ю', 'е', 'і'],
    р: ['я', 'ё', 'ю', 'е', 'і'],
    // дзеканне / цеканне — мяккіх Д і Т няма
    д: ['я', 'ё', 'ю', 'е', 'і'],
    т: ['я', 'ё', 'ю', 'е', 'і'],
    // заднеязычныя мяккія толькі перад І і Е
    г: ['я', 'ё', 'ю', 'ы'],
    к: ['я', 'ё', 'ю', 'ы'],
    х: ['я', 'ё', 'ю', 'ы']
  }),
  letterPattern: /[а-яёіў]/i
};

const UK = {
  // Ґ трапляється в кількох словах — у складах її не беремо.
  consonants: [
    'б', 'в', 'г', 'д', 'ж', 'з', 'к', 'л', 'м', 'н',
    'п', 'р', 'с', 'т', 'ф', 'х', 'ц', 'ч', 'ш', 'щ'
  ],
  vowels: ['а', 'о', 'у', 'и', 'е', 'я', 'ю', 'є', 'і', 'ї'],
  // И не починає склад, Ї після приголосної не буває (див. нижче).
  nonInitialVowels: ['и'],
  softSign: 'ь',
  signs: ['ь', 'ʼ', '’', "'"],
  // Ь пишеться тільки після Д, З, Л, Н, С, Т, Ц
  softSignInvalidConsonants: ['б', 'п', 'в', 'м', 'ф', 'ж', 'ч', 'ш', 'щ', 'р', 'г', 'к', 'х'],
  invalidSyllables: (() => {
    const list = buildInvalid({
      ж: ['я', 'ю', 'є'],
      ч: ['я', 'ю', 'є'],
      ш: ['я', 'ю', 'є'],
      щ: ['я', 'ю', 'є'],
      г: ['я', 'ю', 'є'],
      к: ['я', 'ю', 'є'],
      х: ['я', 'ю', 'є'],
      р: ['є'],
      ц: ['є'],
      // Є після приголосної буває майже лише в Л, Н, Т (синє, останнє,
      // життєвий). Після губних вона вимагає апострофа: б'є, п'є, в'є.
      б: ['є'],
      п: ['є'],
      в: ['є'],
      м: ['є'],
      ф: ['є'],
      д: ['є'],
      з: ['є'],
      с: ['є']
    });
    // Ї ніколи не стоїть після приголосної — тільки на початку слова
    // або після голосної: їжак, мої, з'їзд.
    for (const c of ['б', 'в', 'г', 'д', 'ж', 'з', 'к', 'л', 'м', 'н',
      'п', 'р', 'с', 'т', 'ф', 'х', 'ц', 'ч', 'ш', 'щ']) {
      list.push(c + 'ї');
    }
    return list;
  })(),
  letterPattern: /[а-щьюяєіїґ]/i
};

export const ALPHABETS = { ru: RU, be: BE, uk: UK };

/**
 * Алфавит языка (с откатом на русский для неизвестного кода).
 * @param {string} lang - 'ru' | 'be' | 'uk'
 */
export const getAlphabet = (lang) => ALPHABETS[lang] || ALPHABETS[DEFAULT_LANGUAGE];

export const getConsonants = (lang) => getAlphabet(lang).consonants;
export const getVowels = (lang) => getAlphabet(lang).vowels;
export const getSoftSign = (lang) => getAlphabet(lang).softSign;

/** Гласные, с которых может начинаться слог (для порядка «Гласная + Согласная»). */
export const getInitialVowels = (lang) => {
  const alphabet = getAlphabet(lang);
  return alphabet.vowels.filter(v => !alphabet.nonInitialVowels.includes(v));
};

/**
 * Может ли после согласной стоять мягкий знак (Н → НЬ).
 * @param {string} consonant
 * @param {string} lang
 */
export const canTakeSoftSign = (consonant, lang) => {
  const alphabet = getAlphabet(lang);
  return alphabet.consonants.includes(consonant) &&
    !alphabet.softSignInvalidConsonants.includes(consonant);
};

/**
 * Согласная ли это буква в данном языке.
 * @param {string} letter
 * @param {string} lang
 */
export const isConsonant = (letter, lang) =>
  getAlphabet(lang).consonants.includes((letter || '').toLowerCase());

/**
 * Гласная ли это буква. Всё, что не гласная (согласные, й, ў, ь, ъ, апостроф),
 * считается «не гласной» — этого достаточно для раскраски букв.
 * @param {string} letter
 * @param {string} lang
 */
export const isVowel = (letter, lang) =>
  getAlphabet(lang).vowels.includes((letter || '').toLowerCase());

/**
 * Допустим ли слог «согласная + гласная» по правилам орфографии языка.
 * @param {string} consonant
 * @param {string} vowel
 * @param {string} lang
 */
export const isValidSyllable = (consonant, vowel, lang) =>
  !getAlphabet(lang).invalidSyllables.includes(consonant + vowel);

/**
 * Все гласные, которые можно поставить после данной согласной.
 * @param {string} consonant
 * @param {string} lang
 */
export const getValidVowelsForConsonant = (consonant, lang) =>
  getVowels(lang).filter(vowel => isValidSyllable(consonant, vowel, lang));
