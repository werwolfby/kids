/**
 * Возвращает слово-пример для слога или null.
 * @param {string} syllable
 * @param {string} lang - 'ru' | 'be' | 'uk'
 * @returns {string|null}
 */
export const getWordForSyllable = (syllable, lang = DEFAULT_LANGUAGE) => {
  if (!syllable) return null;
  const map = wordsForSyllable[lang] || wordsForSyllable[DEFAULT_LANGUAGE];
  return map[syllable.toLowerCase()] || null;
};
