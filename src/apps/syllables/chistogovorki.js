/**
 * Возвращает чистоговорку для слога или null, если её нет.
 * @param {string} syllable
 * @param {string} lang - 'ru' | 'be' | 'uk'
 * @returns {string|null}
 */
export const getChistogovorka = (syllable, lang = DEFAULT_LANGUAGE) => {
  if (!syllable) return null;
  const map = chistogovorki[lang] || chistogovorki[DEFAULT_LANGUAGE];
  return map[syllable.toLowerCase()] || null;
};
